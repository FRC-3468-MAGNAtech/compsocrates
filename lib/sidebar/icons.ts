export type SidebarIconKey = keyof typeof SIDEBAR_ICONS;

export const SIDEBAR_ICON_KEYS = Object.keys(SIDEBAR_ICONS) as SidebarIconKey[];

export const isSidebarIconKey = (key: unknown): key is SidebarIconKey => typeof key === "string" && Object.hasOwn(SIDEBAR_ICONS, key);

/** The icon for a stored key, or `fallback` (the page's own icon) when the key is missing or unknown. */
export function sidebarIcon(key: string | undefined, fallback: LucideIcon = Folder): LucideIcon {
  return isSidebarIconKey(key) ? SIDEBAR_ICONS[key] : fallback;
}
